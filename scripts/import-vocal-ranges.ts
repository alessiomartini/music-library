/**
 * Copies the vocal measurements of music-library-offline (output/vocal/<slug>.json,
 * from pipeline/audio_first/vocal_distribution.py) into src/data/songs/vocalRanges.ts.
 *
 * Run with:  npm run import:vocal-ranges [-- path/to/music-library-offline]
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { songs } from '../src/data/songs';
import type { VocalProfile } from '../src/lib/vocalRange';

const OFFLINE = process.argv[2] ?? '../music-library-offline';
const DIR = `${OFFLINE}/output/vocal`;
const OUT = 'src/data/songs/vocalRanges.ts';
const slugs = new Set(songs.map((s) => s.slug));

const out: Record<string, VocalProfile> = {};
for (const file of readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) {
  const slug = file.replace(/\.json$/, '');
  if (!slugs.has(slug)) {
    console.warn(`  skipping ${file}: no song with slug "${slug}"`);
    continue;
  }
  const v = JSON.parse(readFileSync(`${DIR}/${file}`, 'utf8')) as VocalProfile;
  if (!v.countHistogram) throw new Error(`${file} predates the count histogram: re-run vocal_distribution.py`);
  out[slug] = v;
}

const q = (v: unknown) => JSON.stringify(v);
writeFileSync(OUT, [
  "import type { VocalProfile } from '../../lib/vocalRange';",
  '',
  '// Generated by scripts/import-vocal-ranges.ts from music-library-offline/output/vocal. Do not edit by hand.',
  'export const vocalRanges: Record<string, VocalProfile> = {',
  ...Object.keys(out).map((k) => `  ${q(k)}: ${q(out[k])},`),
  '};',
  '',
].join('\n'));
console.log(`${Object.keys(out).length} vocal profiles → ${OUT}`);
