/**
 * Finds covers of songs that have no Wikipedia page, from MusicBrainz (open, keyless), and writes
 * src/data/songs/knownCovers.ts (slug -> other artists' recordings of the same work).
 *
 * For each song without an entry in history.ts (classical pieces skipped: their MusicBrainz titles differ): searches the work by exact title + original artist,
 * accepts it only if unambiguous (src/lib/musicbrainzCovers.ts: exact normalized title, original artist
 * tied to the work as writer or as artist of one of its recordings, exactly one such work), then lists
 * the work's recordings and keeps those by other artists. Precision over recall.
 *
 * 1 request/second (MusicBrainz rule), User-Agent = the repo URL. Resumable: songs already in the output or
 * already checked (node_modules/.cache/musicbrainz-covers.json) are skipped. Stops on repeated errors or
 * after MAX_MINUTES (default 45).
 *
 * Run with:  npm run fetch:musicbrainz-covers   (optional: LIMIT=50, MAX_MINUTES=30)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { songs } from '../src/data/songs';
import { songHistory } from '../src/data/songs/history';
import { knownCovers } from '../src/data/songs/knownCovers';
import { artistNames, norm, pickCovers, pickWork, type KnownCover, type MbRecording, type MbWork } from '../src/lib/musicbrainzCovers';

const OUT = 'src/data/songs/knownCovers.ts';
const TRIED = 'node_modules/.cache/musicbrainz-covers.json';
const UA = 'music-library (https://github.com/alessiomartini/music-library)';
const API = 'https://musicbrainz.org/ws/2';
const LIMIT = Number(process.env.LIMIT) || Infinity;
const DEADLINE = Date.now() + (Number(process.env.MAX_MINUTES) || 45) * 60_000;
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
mkdirSync('node_modules/.cache', { recursive: true });

let last = 0;
async function get(path: string): Promise<any> {
  for (let attempt = 0; attempt < 5; attempt++) {
    await sleep(Math.max(0, last + 1500 - Date.now()) + attempt * 5000);
    last = Date.now();
    const r = await fetch(`${API}/${path}${path.includes('?') ? '&' : '?'}fmt=json`, { headers: { 'User-Agent': UA } }).catch(() => null);
    if (r?.ok) return r.json();
    console.log(`  HTTP ${r?.status ?? 'error'} for ${path.slice(0, 60)}, retrying`);
  }
  throw new Error(`Could not fetch ${path}`);
}

const lucene = (s: string) => `"${s.replace(/["\\]/g, ' ')}"`;
const WRITER = new Set(['composer', 'lyricist', 'writer', 'librettist']);

async function searchWorks(title: string, artist: string): Promise<MbWork[]> {
  const j = await get(`work?query=${encodeURIComponent(`work:${lucene(title)} AND artist:${lucene(artist)}`)}&limit=10`);
  return (j.works ?? []).map((w: any) => ({
    id: w.id,
    title: w.title,
    score: w.score,
    writers: (w.relations ?? []).filter((r: any) => WRITER.has(r.type) && r.artist).map((r: any) => r.artist.name),
    recordingIds: (w.relations ?? []).filter((r: any) => r.type === 'performance' && r.recording).map((r: any) => r.recording.id),
  }));
}

/** Ids of recordings whose artist credit is the original artist (for works without a writer match). */
async function originalRecordings(title: string, artist: string): Promise<Set<string>> {
  const j = await get(`recording?query=${encodeURIComponent(`recording:${lucene(title)} AND artist:${lucene(artist)}`)}&limit=25`);
  return new Set(
    (j.recordings ?? [])
      .filter((r: any) => r.score >= 90 && norm(r.title) === norm(title) && (r['artist-credit'] ?? []).some((a: any) => norm(a.name) === norm(artist)))
      .map((r: any) => r.id as string),
  );
}

async function workRecordings(workId: string): Promise<MbRecording[]> {
  const j = await get(`recording?work=${workId}&inc=artist-credits&limit=100`);
  return (j.recordings ?? []).map((r: any) => ({
    id: r.id,
    title: r.title,
    artist: (r['artist-credit'] ?? []).map((a: any) => `${a.name}${a.joinphrase ?? ''}`).join('').trim(),
    artists: (r['artist-credit'] ?? []).map((a: any) => a.name),
    ...(/^\d{4}/.test(r['first-release-date'] ?? '') && { year: Number(r['first-release-date'].slice(0, 4)) }),
  }));
}

const found: Record<string, KnownCover[]> = { ...knownCovers };
const tried: Record<string, string> = existsSync(TRIED) ? JSON.parse(readFileSync(TRIED, 'utf8')) : {};

function save() {
  const rows = Object.keys(found).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(found[k])},`);
  writeFileSync(OUT, `import type { KnownCover } from '../../lib/musicbrainzCovers';\n\n// Other artists' recordings of the same MusicBrainz work (CC0 data), song slug -> covers.\n// Generated by \`npm run fetch:musicbrainz-covers\` (src/lib/musicbrainzCovers.ts has the matching rule). Do not edit by hand.\nexport const knownCovers: Record<string, KnownCover[]> = {\n${rows.join('\n')}\n};\n`);
  writeFileSync(TRIED, JSON.stringify(tried));
}

const todo = songs.filter((s) => !songHistory[s.slug] && !s.classical && !(s.slug in tried) && !(s.slug in found)).slice(0, LIMIT);
console.log(`${todo.length} songs to check (${Object.keys(tried).length} already checked, ${Object.keys(found).length} with covers)`);
let n = 0;
try {
  for (const s of todo) {
    if (Date.now() > DEADLINE) { console.log('Time cap reached, stopping.'); break; }
    const artist = artistNames(s.artist)[0] ?? s.artist;
    let status = 'none';
    if (artist && !/^(traditional|irish traditional|unknown|various artists)$/i.test(artist)) {
      let works = await searchWorks(s.title, artist);
      let work = pickWork(s.title, s.artist, works, new Set());
      if (!work && works.some((w) => w.score >= 90 && norm(w.title) === norm(s.title))) {
        work = pickWork(s.title, s.artist, works, await originalRecordings(s.title, artist));
      }
      if (work) {
        const covers = pickCovers(s.title, s.artist, await workRecordings(work.id));
        if (covers.length) { found[s.slug] = covers; status = `ok ${covers.length}`; } else status = 'work, no covers';
      } else if (works.some((w) => norm(w.title) === norm(s.title))) status = 'no unambiguous work';
    }
    tried[s.slug] = status;
    console.log(`${++n}/${todo.length} ${s.slug}: ${status}`);
    if (n % 25 === 0) save();
  }
} finally {
  save();
}
console.log(`Done: ${Object.keys(found).length} songs with covers, ${Object.keys(tried).length} checked.`);
