/**
 * Finds the direct YouTube video of the original recording of each song and writes
 * src/data/songs/youtubeDirect.ts (slug -> video id). Songs not matched reliably keep the search link.
 *
 * For each song without a curated YouTube link: searches "<artist> <title>", reads the candidates from
 * ytInitialData and accepts one only if its title contains the song title and the channel is the artist's
 * (or "- Topic" / VEVO) or the title names the artist, rejecting live/cover/karaoke/lyrics... (see
 * src/lib/youtubeLink.ts). The accepted video is then confirmed with oEmbed.
 *
 * Sequential, ~1.5 s between requests. Resumable: songs already in the output (or already tried, see
 * node_modules/.cache/youtube-direct.json) are skipped. Stops gracefully on 429 / consent page.
 *
 * Run with:  npm run fetch:youtube-direct   (optional: LIMIT=50)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { songs } from '../src/data/songs';
import { youtubeDirect } from '../src/data/songs/youtubeDirect';
import { pickOriginal, type YoutubeCandidate } from '../src/lib/youtubeLink';

const OUT = 'src/data/songs/youtubeDirect.ts';
const TRIED = 'node_modules/.cache/youtube-direct.json';
const UA = 'Mozilla/5.0 (music-library link lookup)';
const run = promisify(execFile);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
mkdirSync('node_modules/.cache', { recursive: true });

class RateLimited extends Error {}

async function curl(url: string): Promise<{ status: number; text: string }> {
  // curl exits non-zero on redirect loops (47), which is how YouTube answers when it blocks us.
  const { stdout } = await run('curl', ['-s', '-L', '-m', '30', '-A', UA, '-H', 'Accept-Language: en', '-w', '\n%{http_code}', url], { maxBuffer: 64 << 20 }).catch((e: { stdout?: string }) => {
    throw new RateLimited(`curl failed (${(e.stdout ?? '').trim().replace(/\s+/g, ' ')})`);
  });
  const i = stdout.lastIndexOf('\n');
  return { status: Number(stdout.slice(i + 1)), text: stdout.slice(0, i) };
}

async function search(q: string, attempt = 0): Promise<YoutubeCandidate[]> {
  const { status, text } = await curl(`https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`);
  if (status === 429 || text.includes('consent.youtube.com')) throw new RateLimited(`status ${status}`);
  const m = text.match(/ytInitialData = (\{.*?\});<\/script>/s);
  if (!m) {
    // Possibly a transient bad page: retry twice with a pause before giving up.
    if (attempt >= 2) throw new RateLimited('no ytInitialData');
    await sleep(10000 * (attempt + 1));
    return search(q, attempt + 1);
  }
  const out: YoutubeCandidate[] = [];
  const walk = (o: unknown): void => {
    if (!o || typeof o !== 'object') return;
    const v = o as Record<string, any>;
    if (v.videoRenderer?.videoId) {
      const r = v.videoRenderer;
      out.push({ id: r.videoId, title: r.title?.runs?.map((x: any) => x.text).join('') ?? '', channel: r.ownerText?.runs?.[0]?.text ?? '' });
    }
    for (const k of Object.keys(v)) walk(v[k]);
  };
  walk(JSON.parse(m[1]));
  return out.slice(0, 6);
}

async function oembedOk(id: string, c: YoutubeCandidate): Promise<boolean> {
  const { status, text } = await curl(`https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${id}&format=json`);
  if (status === 429) throw new RateLimited('oembed 429');
  if (status !== 200) return false;
  const j = JSON.parse(text) as { title: string };
  return j.title === c.title;
}

const direct: Record<string, string> = { ...youtubeDirect };
const tried: Record<string, string> = existsSync(TRIED) ? JSON.parse(readFileSync(TRIED, 'utf8')) : {};

function save() {
  const rows = Object.keys(direct).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(direct[k])},`);
  writeFileSync(OUT, `// Direct YouTube video of the original recording, song slug -> video id.\n// Generated by \`npm run fetch:youtube-direct\`; songs missing here keep the search link.\nexport const youtubeDirect: Record<string, string> = {\n${rows.join('\n')}\n};\n`);
  writeFileSync(TRIED, JSON.stringify(tried));
}

const todo = songs.filter((s) => !s.classical && (!s.links.youtube || s.links.youtube.includes('/results')) && !direct[s.slug] && !tried[s.slug]);
const limit = Number(process.env.LIMIT) || todo.length;
console.log(`${todo.length} songs to try (of ${songs.length}), limit ${limit}`);
let n = 0;
try {
  for (const s of todo.slice(0, limit)) {
    await sleep(1500);
    const cands = await search(`${s.artist.split(/,| & /)[0]} ${s.title}`);
    const hit = pickOriginal(cands, s.title, s.artist);
    await sleep(500);
    if (hit && (await oembedOk(hit.id, hit))) {
      direct[s.slug] = hit.id;
      tried[s.slug] = 'ok';
    } else {
      tried[s.slug] = 'no';
      console.log(`unmatched: ${s.title} / ${s.artist}`);
    }
    if (++n % 25 === 0) { save(); console.log(`${n} done, ${Object.keys(direct).length} matched`); }
  }
} catch (e) {
  if (e instanceof RateLimited) console.log(`Rate limited (${e.message}): stopping, progress saved.`);
  else throw e;
}
save();
console.log(`matched ${Object.keys(direct).length} / ${songs.length}`);
