/**
 * "Mine" ranking: how much Alessio really listens to each song, from the Spotify extended
 * streaming history (a private export, never committed). Counts plays of at least 30 s on
 * the Spotify recordings linked to a song, turns them into a percentile 0-100 among all
 * songs, and writes ONLY that percentile to src/data/songs/mine.ts (no counts, no dates).
 *
 * Run with:  npm run compute:mine [-- path/to/extended-streaming-history.zip]
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { songs } from '../src/data/songs';
import { percentiles, trackIds } from '../src/lib/ranking';

const ZIP = process.argv[2] ?? 'E:/Alessio/Dati-personali/spotify/2026-10-18_extended-streaming-history.zip';
const MIN_MS = 30_000;

const dir = mkdtempSync(join(tmpdir(), 'spotify-history-'));
const plays = new Map<string, number>();
try {
  if (process.platform === 'win32') {
    execFileSync('powershell', ['-NoProfile', '-Command', 'Expand-Archive -LiteralPath $env:ZIP -DestinationPath $env:DEST'], { env: { ...process.env, ZIP, DEST: dir } });
  } else execFileSync('unzip', ['-q', ZIP, '-d', dir]);
  const files = (d: string): string[] => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? files(join(d, e.name)) : [join(d, e.name)]));
  for (const f of files(dir).filter((f) => /Streaming_History_Audio.*\.json$/.test(f))) {
    for (const r of JSON.parse(readFileSync(f, 'utf8')) as { ms_played: number; spotify_track_uri: string | null }[]) {
      const id = r.spotify_track_uri?.match(/^spotify:track:(\w+)$/)?.[1];
      if (id && r.ms_played >= MIN_MS) plays.set(id, (plays.get(id) ?? 0) + 1);
    }
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}

const raw = new Map(songs.map((s) => [s.slug, trackIds(s).reduce((n, id) => n + (plays.get(id) ?? 0), 0)]));
const pct = percentiles(raw);
const listened = songs.filter((s) => raw.get(s.slug)! > 0);
writeFileSync('src/data/songs/mine.ts', [
  '// Generated by scripts/compute-mine.ts: percentile 0-100 of how much each song is listened to (songs never',
  '// played are absent = 0). Derived score only; the listening history itself is private and not in the repo.',
  'export const mine: Record<string, number> = {',
  ...listened.map((s) => `  ${JSON.stringify(s.slug)}: ${Math.round(pct.get(s.slug)!)},`).sort(),
  '};', '',
].join('\n'));
console.log(`${songs.length} songs, ${listened.length} with at least one play ≥30 s → src/data/songs/mine.ts`);
