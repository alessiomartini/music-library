/**
 * Looks up who posted each saved Instagram post (public oEmbed endpoint) and
 * writes src/data/songs/instagramAuthors.ts, so version links can name the
 * person who made the cover. Responses are cached in
 * node_modules/.cache/instagram/.
 *
 * Run with:  npm run fetch:instagram-authors
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { songs } from '../src/data/songs';

const OUT = 'src/data/songs/instagramAuthors.ts';
const CACHE = 'node_modules/.cache/instagram';
mkdirSync(CACHE, { recursive: true });
const run = promisify(execFile);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function author(post: string): Promise<string | null> {
  const file = `${CACHE}/${createHash('sha1').update(post).digest('hex')}`;
  let body = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (body === null) {
    await sleep(1500);
    // curl rather than fetch: it honours the HTTPS_PROXY of sandboxed environments.
    const url = `https://www.instagram.com/api/v1/oembed/?url=${encodeURIComponent(post)}`;
    body = await run('curl', ['-s', '-m', '30', url]).then((r) => r.stdout).catch(() => '');
    if (body.startsWith('{')) writeFileSync(file, body);
  }
  try {
    return (JSON.parse(body) as { author_name?: string }).author_name ?? null;
  } catch {
    return null;
  }
}

const posts = [...new Set(songs.flatMap((s) => s.links.instagram ?? []))];
const authors: [string, string][] = [];
for (const post of posts) {
  const name = await author(post);
  if (name) authors.push([post, name]);
}
const q = (s: string) => JSON.stringify(s);
writeFileSync(OUT, [
  '// Generated by scripts/fetch-instagram-authors.ts. Do not edit by hand.',
  '/** Instagram account that published each saved post. */',
  'export const instagramAuthors: Record<string, string> = {',
  ...authors.sort(([a], [b]) => a.localeCompare(b)).map(([post, name]) => `  ${q(post)}: ${q(name)},`),
  '};',
  '',
].join('\n'));
console.log(`${posts.length} posts → ${authors.length} authors → ${OUT}`);
