/**
 * Genres of each artist from Wikidata (P136 "genre"), for the artists whose Wikidata id
 * scripts/fetch-artists.ts already found. Nothing is guessed: an artist with no P136 gets
 * no entry (the site shows "No genre"). Output: src/data/songs/genres.ts.
 *
 * Run with:  npm run fetch:genres
 */
import { writeFileSync } from 'node:fs';
import { artists } from '../src/data/songs/artists';

const API = 'https://www.wikidata.org/w/api.php';
async function entities(ids: string[], props: string) {
  const url = `${API}?action=wbgetentities&format=json&ids=${ids.join('|')}&props=${props}&languages=en`;
  let r: Response;
  for (let wait = 5000; ; wait = Math.min(wait * 2, 120_000)) { // Wikimedia throttles at times: back off
    r = await fetch(url, { headers: { 'User-Agent': 'music-library/1.0 (personal project)' } });
    if (r.ok) break;
    if (r.status !== 429 && r.status < 500) throw new Error(`${r.status} ${url}`);
    await new Promise((res) => setTimeout(res, wait));
  }
  await new Promise((res) => setTimeout(res, 500));
  return ((await r.json()) as { entities: Record<string, { claims?: Record<string, { mainsnak: { datavalue?: { value: { id: string } } } }[]>; labels?: { en?: { value: string } } }> }).entities;
}
const chunks = <T>(a: T[], n = 50) => Array.from({ length: Math.ceil(a.length / n) }, (_, i) => a.slice(i * n, i * n + n));

const byQid = new Map<string, string[]>();
for (const batch of chunks([...new Set(Object.values(artists).map((a) => a.wikidata))])) {
  const e = await entities(batch, 'claims');
  for (const [qid, v] of Object.entries(e)) {
    const ids = (v.claims?.P136 ?? []).map((c) => c.mainsnak.datavalue?.value.id).filter((x): x is string => !!x);
    if (ids.length) byQid.set(qid, ids);
  }
}
const labels = new Map<string, string>();
for (const batch of chunks([...new Set([...byQid.values()].flat())])) {
  for (const [id, v] of Object.entries(await entities(batch, 'labels'))) if (v.labels?.en) labels.set(id, v.labels.en.value);
}

const out: Record<string, string[]> = {};
for (const [name, a] of Object.entries(artists)) {
  const g = [...new Set((byQid.get(a.wikidata) ?? []).map((id) => labels.get(id)).filter((x): x is string => !!x))];
  if (g.length) out[name] = g;
}
writeFileSync('src/data/songs/genres.ts', [
  '// Generated by scripts/fetch-genres.ts (Wikidata P136). Artists with no genre on Wikidata are absent. Do not edit by hand.',
  'export const genres: Record<string, string[]> = {',
  ...Object.keys(out).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`),
  '};', '',
].join('\n'));
console.log(`${Object.keys(artists).length} artists → ${Object.keys(out).length} with genres → src/data/songs/genres.ts`);
